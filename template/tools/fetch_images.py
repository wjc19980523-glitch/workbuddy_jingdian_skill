"""Step 4 — download the photos named in spots.json, with licence + AI checks.

usage: python3 -I fetch_images.py <cityDir>

For every spot image  {"id": "s05a", "commons": "File:....jpg", "page": 3?, "width": 1600?, "crop": [l,t,r,b]?,
                       "caption": "...", "credit": ""?}
  * reads the Wikimedia Commons file page metadata (licence, author, description, categories)
  * REJECTS the file unless the licence is public domain / CC0 / CC BY / CC BY-SA (no NC, no ND, no fair use)
  * REJECTS the file if Commons categorises or describes it as AI-generated
  * downloads the original (or a thumbnail of <width>), applies the optional crop, writes assets/img/<id>.jpg
    (RGB, short side ≤ 2400 px, long side ≤ 9000 px) and assets/img/meta.json
  * fills an empty "credit" with author · licence · Wikimedia Commons (CC BY/BY-SA require attribution on screen)
Images supplied by the user instead ("ai": true marks an AI-generated picture → the film labels it 「AI生成画面」 on screen): {"id": ..., "local": "path", "license": "...", "author": "...", "sourceUrl": "..."}
  are copied as-is and listed as 待核对 in image-sources.md unless the licence passes the same whitelist.
Rejected images are removed from spots.json and listed in assets/img/rejected.json; a node left without images
gets a text card.
"""
import json, os, re, shutil, sys, time
from PIL import Image, ImageOps, ImageEnhance

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import commons  # noqa: E402

Image.MAX_IMAGE_PIXELS = None
OK_LIC = re.compile(r'^(public domain|pd\b|pd-|cc0|cc[- ]by(-sa)?[- ]?\d|cc[- ]by(-sa)?$|no restrictions|attribution)', re.I)
BAD_LIC = re.compile(r'\b(nc|nd|non-?commercial|no ?deriv|fair use|all rights reserved|copyrighted)\b', re.I)
AI = re.compile(r'(ai[- ]generated|generated by ai|midjourney|dall[- ·]?e|stable diffusion|text-to-image|生成式|AI生成|人工智能生成)', re.I)


def licence_ok(lic):
    return bool(lic) and bool(OK_LIC.search(lic.strip())) and not BAD_LIC.search(lic)


def categories(title):
    r = commons.call(dict(action='query', titles=title, prop='categories', cllimit='max'))
    pg = next(iter(r['query']['pages'].values()))
    return [c['title'] for c in pg.get('categories', [])]


def norm(src, dst, crop=None):
    im = ImageOps.exif_transpose(Image.open(src))   # phone photos: apply the EXIF rotation
    if im.mode in ('RGBA', 'LA', 'P'):
        im = im.convert('RGBA'); bg = Image.new('RGBA', im.size, (236, 229, 212, 255)); bg.alpha_composite(im); im = bg
    im = im.convert('RGB')
    if crop:
        l, t, r, b = crop; W, H = im.size
        im = im.crop((int(l * W), int(t * H), int(r * W), int(b * H)))
    k = min(1.0, 2400 / min(im.size), 9000 / max(im.size))
    if k < 1:
        im = im.resize((round(im.width * k), round(im.height * k)), Image.LANCZOS)
    im = ImageEnhance.Color(ImageEnhance.Contrast(im).enhance(1.07)).enhance(1.16)   # the film's grade, baked in
    im.save(dst, quality=92)
    return im.size


def credit_for(x):
    lic = x['license'] or ''
    if re.match(r'(public domain|pd|cc0|no restrictions)', lic, re.I):
        return '公有领域 · Wikimedia Commons'
    who = re.sub(r'\s+', ' ', x.get('artist') or '').strip()
    who = re.sub(r'^(Own work|自己的作品)\s*', '', who)
    who = re.sub(r'^User:', '', who) or '佚名'
    return f'摄影 {who[:40]} · {lic} · Wikimedia Commons'


def main():
    CITY = os.path.abspath(sys.argv[1])
    IMG = os.path.join(CITY, 'assets', 'img'); RAW = os.path.join(CITY, 'build', 'imgraw')
    os.makedirs(IMG, exist_ok=True); os.makedirs(RAW, exist_ok=True)
    NP = os.path.join(CITY, 'spots.json')
    data = json.load(open(NP, encoding='utf-8'))
    cp = os.path.join(CITY, 'research', 'image_candidates.json')
    cand = json.load(open(cp, encoding='utf-8')) if os.path.exists(cp) else {}

    meta_p = os.path.join(IMG, 'meta.json')
    meta = json.load(open(meta_p, encoding='utf-8')) if os.path.exists(meta_p) else {}
    rejected = []
    for n in data['spots']:
        keep = []
        for spec in n.get('images', []):
            if spec.get('pick'):        # candidate code from find_images.py → Commons file
                items = {x['code']: x for v in cand.values() for x in v['items']}
                if spec['pick'] not in items:
                    rejected.append(dict(id=spec.get('id', ''), node=n['id'], file=spec['pick'], why='编号不在 research/images.md 候选里'))
                    continue
                spec['commons'] = items[spec['pick']]['title']
            spec['id'] = f"{n['id']}{'abcdef'[len(keep)]}"
            iid = spec['id']
            if spec.get('local'):
                dst = os.path.join(IMG, iid + '.jpg')
                spec['w'], spec['h'] = norm(spec['local'], dst, spec.get('crop'))
                meta[iid] = dict(title=os.path.basename(spec['local']), license=spec.get('license', ''), artist=spec.get('author', ''),
                                 page=spec.get('sourceUrl', ''), node=n['id'], user_supplied=True, ai=bool(spec.get('ai')),
                                 review=not licence_ok(spec.get('license', '')))
                spec.setdefault('credit', 'AI 生成画面' if spec.get('ai') else (spec.get('author', '') + ' · ' + spec.get('license', '')))
                keep.append(spec); continue
            width = spec.get('width', None)
            x = commons.info([spec['commons']], width, spec.get('page'))[0]
            if not x.get('url'):
                rejected.append(dict(id=iid, node=n['id'], file=spec['commons'], why='Commons 上找不到该文件')); continue
            cats = categories(spec['commons'])
            why = None
            if not licence_ok(x['license']):
                why = f"授权不合规：{x['license'] or '未标注'}"
            elif AI.search(' '.join(cats) + ' ' + (x.get('desc') or '')):
                why = 'Commons 分类/说明显示为 AI 生成图'
            if why:
                rejected.append(dict(id=iid, node=n['id'], file=spec['commons'], why=why)); print('REJECT', iid, why); continue
            url = x['thumb'] if x.get('thumb') else x['url']
            ext = os.path.splitext(url.split('?')[0])[1].lower() or '.jpg'
            raw = os.path.join(RAW, iid + ext)
            if not (os.path.exists(raw) and os.path.getsize(raw) > 1000 and meta.get(iid, {}).get('title') == spec['commons']):
                commons.download(url, raw)
                time.sleep(1.5)  # ease Commons 429 rate limits
            size = norm(raw, os.path.join(IMG, iid + '.jpg'), spec.get('crop'))
            x.update(id=iid, node=n['id'], raw=os.path.relpath(raw, CITY), fetched=url, categories=cats[:30],
                     crop=spec.get('crop'), pdfpage=spec.get('page'), size=size)
            meta[iid] = x
            spec['credit'] = credit_for(x)
            spec['w'], spec['h'] = size
            keep.append(spec)
            print('ok', iid, x['license'], (x['artist'] or '')[:30], size, flush=True)
        if 'images' in n:
            n['images'] = keep
    json.dump(meta, open(meta_p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    json.dump(rejected, open(os.path.join(IMG, 'rejected.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    json.dump(data, open(NP, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('images', len(meta), 'rejected', len(rejected))


if __name__ == '__main__':
    main()
